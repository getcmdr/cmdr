//! Every key a page-drawn bar shows, written where the frontend's `bar-keys.test.ts` reads it to
//! prove each one FIRES: in the viewer and the bar-less child windows through `barRowForKey`, and
//! in the main window through its command dispatcher. Off macOS no native bar registers anything
//! (D5, task 63 of `docs/specs/windows-port-plan.md`), so a shown key that no page code runs would
//! be a lie the parity test's text comparison can't see.
//!
//! Each line is `platform`, `window` (`main` or `viewer`), the row's menu id, its
//! `aria-keyshortcuts`, and the command the row stands for (empty for a row with its own lane). A
//! stale file fails here with the text to write.

use super::viewer::{ViewerBarInputs, viewer_bar_view};
use super::{BarInputs, BarMenuView, Row, bar_view};
use crate::ids::{
    SHOW_HIDDEN_FILES_ID, VIEW_MODE_BRIEF_LEFT_ID, VIEW_MODE_FULL_LEFT_ID, VIEW_SHOW_HIDDEN_COMMAND_ID,
    menu_id_to_command,
};
use crate::spec::Platform;

const FIXTURE: &str = include_str!("bar_keys.tsv");

fn keyed_rows(rows: &[Row], into: &mut Vec<(String, String)>) {
    for row in rows {
        match row {
            Row::Submenu { rows, .. } => keyed_rows(rows, into),
            Row::Item {
                id,
                aria_keyshortcuts: Some(aria),
                ..
            }
            | Row::Check {
                id,
                aria_keyshortcuts: Some(aria),
                ..
            } => into.push((id.clone(), aria.clone())),
            _ => {}
        }
    }
}

/// The command a row's key runs in the main window: its mapped command, or the one its own lane
/// stands for (the left pane's view-mode checks carry the view-mode keys, as `bar_parity_test.rs`
/// reads them). `None` for a row with no command at all (the viewer's).
fn row_command(menu_id: &str) -> Option<&'static str> {
    match menu_id {
        VIEW_MODE_FULL_LEFT_ID => Some("view.fullMode"),
        VIEW_MODE_BRIEF_LEFT_ID => Some("view.briefMode"),
        SHOW_HIDDEN_FILES_ID => Some(VIEW_SHOW_HIDDEN_COMMAND_ID),
        _ => menu_id_to_command(menu_id).map(|(command, _scope)| command),
    }
}

fn lines_for(platform: Platform, window: &str, menus: &[BarMenuView], out: &mut Vec<String>) {
    let mut rows = Vec::new();
    for menu in menus {
        keyed_rows(&menu.rows, &mut rows);
    }
    for (id, aria) in rows {
        let command = row_command(&id).unwrap_or("");
        out.push(format!("{}\t{window}\t{id}\t{aria}\t{command}", platform.wire()));
    }
}

#[test]
fn every_shown_page_bar_key_is_in_the_frontends_fixture() {
    let mut lines = vec![
        "# platform\twindow\tmenu id\taria-keyshortcuts\tcommand. Generated by `crates/cmdr-menu/src/page/bar_keys_test.rs`, ❌ never by hand.".to_string(),
    ];
    for platform in [Platform::Windows, Platform::Linux] {
        lines_for(
            platform,
            "main",
            &bar_view(&BarInputs::fresh(platform), platform),
            &mut lines,
        );
        // Every viewer row live, so a greyed one's key is listed too.
        let viewer = ViewerBarInputs {
            word_wrap: false,
            can_go_back: true,
            can_go_forward: true,
            search_focused: true,
            show_menu_bar: true,
        };
        lines_for(platform, "viewer", &viewer_bar_view(viewer, platform), &mut lines);
    }
    let expected = format!("{}\n", lines.join("\n"));
    assert_eq!(
        FIXTURE, expected,
        "`crates/cmdr-menu/src/page/bar_keys.tsv` drifted from the bars; write this:\n{expected}"
    );
}
